# 運用側 ⑩〜⑭ を ⑭〜⑱ へ（大きい番号から順に退避してから戻す）
SHIFT = [(u"⑭", u""), (u"⑬", u""), (u"⑫", u""),
         (u"⑪", u""), (u"⑩", u"")]
