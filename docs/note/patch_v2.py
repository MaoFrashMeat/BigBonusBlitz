    st = s.index(u"# 7. 壊れ方から見えた4つの型")
    en = s.index(u"# 8. 絵と音は、どうしたか")
    s = s[:st] + TYPES + u"---\n\n" + s[en:]

    a3 = u"## 読者が真似する場合の最小版"
    if a3 in s:
        s = s.replace(a3, COUNT_CHECK + a3, 1)
    else:
        print("MISS: 最小版")

